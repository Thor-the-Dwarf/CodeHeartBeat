public class Datentypen {
    public static void main(String[] args) {
        int anzahl = 12;
        double preis = 2.49;
        boolean verfuegbar = true;
        char kategorie = 'A';
        String artikel = "Apfel";

        System.out.println(artikel + ": " + anzahl + " Stück");
        System.out.println("Preis: " + preis + " Euro");
        System.out.println("Kategorie: " + kategorie);
        System.out.println("Verfügbar: " + verfuegbar);
    }
}
